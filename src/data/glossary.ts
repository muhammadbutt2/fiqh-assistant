export function findGlossaryHits(text: string): GlossaryEntry[] {
  const haystack = text.toLowerCase();
  return GLOSSARY.filter((entry) => entry.forms.some((form) => haystack.includes(form.toLowerCase()) || text.includes(form)));
}
